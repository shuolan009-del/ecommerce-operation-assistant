type RunSeed = {
  id: number;
  thread_id: string;
  workspace_id: number;
  task_id: number | null;
  product_id: number | null;
  requested_by_user_id: number;
  workflow_key: string;
  status: AgentRun["status"];
  current_agent: string | null;
  error: string | null;
  started_at: string;
  finished_at: string | null;
  agent_name: string;
  event_message: string;
  review?: { reviewed_by_user_id: number; decision: AgentRunReview["decision"]; note: string };
};

/** 构造演示 AgentRun，自动装配事件流与（可选的）审批记录。 */
function buildRun(seed: RunSeed): AgentRun {
  const events: AgentRunEvent[] = [
    {
      id: seed.id * 10 + 1,
      event_type: "run.started",
      agent_name: "coordinator",
      operation_name: "dispatch",
      status: "running",
      message: "任务已受理，开始调度。",
      input_snapshot: { workflow_key: seed.workflow_key },
      output_snapshot: {},
      metrics: {},
      trace_id: `demo-trace-${seed.id}`,
      span_id: `demo-span-${seed.id}-1`,
      created_at: seed.started_at,
      updated_at: seed.started_at,
    },
    {
      id: seed.id * 10 + 2,
      event_type: seed.status === "failed" ? "run.failed" : "run.finished",
      agent_name: seed.agent_name,
      operation_name: "execute",
      status: seed.status,
      message: seed.error ?? seed.event_message,
      input_snapshot: {},
      output_snapshot: seed.status === "completed" ? { ok: true } : {},
      metrics: { latency_ms: 1820 },
      trace_id: `demo-trace-${seed.id}`,
      span_id: `demo-span-${seed.id}-2`,
      created_at: seed.finished_at ?? seed.started_at,
      updated_at: seed.finished_at ?? seed.started_at,
    },
  ];

  const reviews: AgentRunReview[] = seed.review
    ? [
        {
          id: seed.id * 10 + 1,
          reviewed_by_user_id: seed.review.reviewed_by_user_id,
          decision: seed.review.decision,
          edited_output: seed.review.decision === "edit_and_approve" ? { edited: true } : {},
          note: seed.review.note,
          created_at: seed.finished_at ?? seed.started_at,
          updated_at: seed.finished_at ?? seed.started_at,
        },
      ]
    : [];

  return {
    id: seed.id,
    thread_id: seed.thread_id,
    workspace_id: seed.workspace_id,
    task_id: seed.task_id,
    product_id: seed.product_id,
    requested_by_user_id: seed.requested_by_user_id,
    workflow_key: seed.workflow_key,
    workflow_version: "1.0.0",
    attempt: 1,
    queue_name: "default",
    status: seed.status,
    current_agent: seed.current_agent,
    revision_count: 0,
    max_revisions: 3,
    budget: { max_tokens: 12000, max_tool_calls: 20 },
    usage: { total_tokens: 4820, tool_calls: 6 },
    version_manifest: { workflow: "1.0.0" },
    context_snapshot: { product_id: seed.product_id },
    draft_output: {},
    quality_report: { passed: seed.status === "completed" },
    final_output: seed.status === "completed" ? { ok: true } : {},
    error: seed.error,
    lease_owner: seed.status === "running" ? "worker-demo-1" : null,
    lease_expires_at: seed.status === "running" ? "2026-10-12T14:20:00+08:00" : null,
    timeout_at: null,
    cancel_requested_at: null,
    started_at: seed.started_at,
    finished_at: seed.finished_at,
    created_at: seed.started_at,
    updated_at: seed.finished_at ?? seed.started_at,
    events,
    reviews,
  };
}

