  diagnosis: Omit<ProductDiagnosis, "id" | "product_id" | "created_at" | "updated_at">;
  adExperiment: Omit<AdExperiment, "id" | "product_id" | "created_at" | "updated_at">;
  promotionLink: Omit<PromotionLink, "id" | "product_id" | "created_at" | "updated_at">;
  generatedAsset: Omit<GeneratedAsset, "id" | "product_id" | "created_at" | "updated_at">;
