type PerformanceSeed = {
  period_start: string;
  period_end: string;
  impressions: number;
  clicks: number;
  conversions: number;
  spend: string;
  revenue: string;
};

/** 构造投放效果记录，CTR / 转化率 / ROI 由数值推导，避免手算出错。 */
function buildPerformance(productId: number, index: number, seed: PerformanceSeed): PerformanceRecord {
  const ctr = seed.impressions > 0 ? ((seed.clicks / seed.impressions) * 100).toFixed(2) + "%" : null;
  const conversionRate =
    seed.clicks > 0 ? ((seed.conversions / seed.clicks) * 100).toFixed(2) + "%" : null;
  const spend = Number(seed.spend);
  const revenue = Number(seed.revenue);
  const roi = spend > 0 ? (revenue / spend).toFixed(2) : null;

  return {
    id: productId * 1000 + index,
    product_id: productId,
    creative_plan_id: null,
    ad_experiment_id: null,
    promotion_link_id: null,
    generated_asset_id: null,
    period_start: seed.period_start,
    period_end: seed.period_end,
    impressions: seed.impressions,
    clicks: seed.clicks,
    ctr,
    conversions: seed.conversions,
    conversion_rate: conversionRate,
    spend: seed.spend,
    revenue: seed.revenue,
    roi,
    notes: index === 1 ? "大促前预热期，转化率略低于日常。" : null,
    created_at: `${seed.period_end}T20:10:00+08:00`,
    updated_at: `${seed.period_end}T20:10:00+08:00`,
  };
}

